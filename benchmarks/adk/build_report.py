"""Build benchmarks/adk/RESULTS.md from results/*.json (no number is typed by hand)."""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / "results"


def load(name: str):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def sci(x, nd=1) -> str:
    return "n/a" if x is None or x != x else f"{x:.{nd}e}"


def yn(b) -> str:
    return "PASS" if b else "FAIL"


def main() -> None:
    g1, g2, g3, g4, g5, g6 = (
        load(f)
        for f in (
            "g1_pca_numerics.json",
            "g2_fel.json",
            "g3_angles_pmf.json",
            "g4_kinetics.json",
            "g5_default_workflows.json",
            "g6_informational.json",
        )
    )
    perf = load("performance_summary.json")
    gates: list[tuple[str, bool]] = []
    L: list[str] = []
    L += [
        "# ADK equilibrium trajectory — results",
        "",
        "Generated by `benchmarks/adk/build_report.py` from `results/*.json`. Pass criteria were committed in `CRITERIA.md` before any result was computed; departures are in `DEVIATIONS.md`. Gates that failed are reported as failed.",
        "",
    ]

    # G0
    gates.append(("G0 input integrity", bool(g1["g0"]["pass"])))
    L += [
        "## G0 — input integrity",
        "",
        f"{yn(g1['g0']['pass'])}: "
        + ", ".join(f"{k} {'ok' if v else 'FAILED'}" for k, v in g1["g0"]["checks"].items()),
        "",
    ]

    # G1
    L += [
        "## G1 — PCA numerics (identical pre-fitted coordinates, no further fit; top 10 modes; reference = independent NumPy covariance + `eigh`)",
        "",
        "| Selection (N frames × D coords) | Tool | rel. eigenvalue error | explained-variance error (pp) | 1 − \\|cos\\| (separated modes) | projection error / SD | gate |",
        "|---|---|---|---|---|---|---|",
    ]
    for sel in ("calpha", "backbone", "heavy"):
        if sel not in g1:
            continue
        d = g1[sel]
        for tool, m in d["tools"].items():
            if "error" in m:
                L.append(
                    f"| {sel} ({d['N']} × {d['D']}) | {tool} | error: {m['error']} | | | | FAIL |"
                )
                if "(auto)" not in tool:
                    gates.append((f"G1 {sel} {tool}", False))
                continue
            verdict = m.get("pass")
            if verdict is None:
                g = "informational (randomised solver)"
            else:
                g = yn(verdict)
                gates.append((f"G1 {sel} {tool}", bool(verdict)))
            L.append(
                f"| {sel} ({d['N']} × {d['D']}) | {tool} | {sci(m['max_rel_eigenvalue_error'])} | {sci(m['max_explained_abs_error_pct'])} | {sci(m['max_one_minus_cos_separated'])} | {sci(m['max_projection_err_over_sd_separated'])} | {g} |"
            )
    L += [
        "",
        "Gates: double-precision tools 1e-6 on every column; GROMACS 1e-4 (eigenvalues, eigenvectors) and 1e-3 (explained variance); GROMACS projections are not applicable (DEVIATIONS D1). `MDTraj+sklearn(auto)` uses scikit-learn's randomised solver and is informational.",
        "",
    ]

    # G2
    L += [
        "## G2 — free-energy landscape, Cα PC1–PC2, 300 K",
        "",
        "| Grid | vs NumPy histogram (registered k_B) | vs NumPy histogram (exact SI k_B, diagnosis only) | vs `gmx sham` |",
        "|---|---|---|---|",
    ]
    for n, d in g2["grids"].items():
        np_, si, sh = d["numpy"], d["numpy_with_exact_SI_kB_diagnosis_only"], d["gmx_sham"]
        gates.append((f"G2 numpy {n}", bool(np_["pass"])))
        gates.append((f"G2 sham {n}", bool(sh["pass"])))
        L.append(
            f"| {n}×{n} ({np_['occupied_in_both']} occupied bins) | {sci(np_['max_abs_diff_kJ_mol'])} kJ/mol — {yn(np_['pass'])} (gate {sci(np_['gate_kJ_mol'], 0)}) | {sci(si['max_abs_diff_kJ_mol'])} kJ/mol | {sci(sh['max_abs_diff_kJ_mol'])} kJ/mol — {yn(sh['pass'])} (gate {sci(sh['gate_kJ_mol'], 0)}) |"
        )
    L += [
        "",
        "The NumPy failure is explained in `DEVIATIONS.md` D4 (the constant written in `CRITERIA.md`); it remains a failure as registered.",
        "",
    ]

    # G3
    L += ["## G3 — angle coordinates and the published PMF", ""]
    a = g3["G3a"]
    gates.append(("G3a definition check", bool(a["pass"])))
    L += [
        f"**G3a (published PMF at the crystal-structure angles, gate ≤ 10 kJ/mol above its minimum): {yn(a['pass'])}**",
        "",
        "| Structure | θ_NMP (°) | θ_LID (°) | published PMF (kJ/mol above its minimum) | backbone-centre variant (°) |",
        "|---|---|---|---|---|",
    ]
    for k, v in a["points"].items():
        L.append(
            f"| {k} | {v['theta_NMP']:.1f} | {v['theta_LID']:.1f} | {v['pmf_kJ_mol']:.1f} | {v['backbone_variant_angles'][0]:.1f}, {v['backbone_variant_angles'][1]:.1f} |"
        )
    mm = g3["pmf_local_minima_informational"]["minima_(NMP_deg,LID_deg,kJ_mol)"]
    L += [
        "",
        f"The published PMF covers NMP {g3['pmf_grid']['NMP_deg'][0]:.0f}–{g3['pmf_grid']['NMP_deg'][1]:.0f}°, LID {g3['pmf_grid']['LID_deg'][0]:.0f}–{g3['pmf_grid']['LID_deg'][1]:.0f}°; its lowest local minima (NMP°, LID°, kJ/mol) are "
        + "; ".join(f"({x:.0f}, {y:.0f}, {z})" for x, y, z in mm[:4])
        + ". Neither crystal structure lies at a minimum, so this check cannot separate a coordinate-frame mismatch from a property of the implicit-solvent PMF.",
        "",
    ]
    b = g3["G3b"]
    gates.append(("G3b ConformAtlas vs NumPy on angles", bool(b["registered_kB"]["pass"])))
    L += [
        f"**G3b (ConformAtlas vs NumPy histogram on the 2° angle grid):** registered k_B {sci(b['registered_kB']['max_abs_diff_kJ_mol'])} kJ/mol — {yn(b['registered_kB']['pass'])}; exact SI k_B {sci(b['exact_SI_kB_diagnosis_only']['max_abs_diff_kJ_mol'])} kJ/mol (diagnosis, DEVIATIONS D4). {b['frames_inside_grid']} of {b['frames_total']} frames fall inside the 64°×64° grid window.",
        "",
    ]
    c = g3["G3c_informational"]
    t = g3["trajectory_angles"]
    dr = g3["trajectory_drift_informational"]
    L += [
        "**G3c (informational, no pass/fail):** "
        f"Spearman ρ between the trajectory landscape and the published PMF over {c['bins_compared_(occupied_and_finite_in_PMF)']} common bins = {c['spearman_rho']:.2f}; trajectory minimum at (NMP, LID) = ({c['trajectory_minimum_deg_(NMP,LID)'][0]:.0f}°, {c['trajectory_minimum_deg_(NMP,LID)'][1]:.0f}°), published minimum at ({c['published_minimum_deg_(NMP,LID)'][0]:.0f}°, {c['published_minimum_deg_(NMP,LID)'][1]:.0f}°), separation {c['minimum_separation_deg']:.0f}°. The published PMF is implicit-solvent umbrella sampling; the trajectory is explicit-water CHARMM27.",
        "",
        f"**The trajectory is not stationary from frame 0.** It starts at (NMP, LID) = ({t['first_frame'][0]:.1f}°, {t['first_frame'][1]:.1f}°), a closed-like state, and block means over ten {dr['block_ns']} ns blocks are NMP {', '.join(str(x) for x in dr['block_mean_NMP_deg'])}° and LID {', '.join(str(x) for x in dr['block_mean_LID_deg'])}°: after the first ~100 ns it remains in the open region, which lies partly outside the published PMF's grid (trajectory range NMP {t['NMP_deg']['min']:.0f}–{t['NMP_deg']['max']:.0f}°, LID {t['LID_deg']['min']:.0f}–{t['LID_deg']['max']:.0f}°).",
        "",
    ]

    # G4
    L += [
        "## G4 — kinetics on one shared discretisation (deeptime k-means, 100 clusters, PC1–PC3; TICA input: top 10 PCs)",
        "",
        "| Lag (frames) | TICA eigenvalues rel. error (gate 1e-8) | active states (ConformAtlas / deeptime) | stationary distribution max abs error (gate 1e-7) | timescales rel. error, top 5 (gate 1e-5) | timescales rel. error, top 4 / |λ|-ordered (diagnosis) |",
        "|---|---|---|---|---|---|",
    ]
    for lag, d in g4["lags"].items():
        m, ti, dg = d["msm"], d["tica"], d["msm_timescale_ordering_diagnosis_only"]
        gates += [
            (f"G4 TICA lag {lag}", bool(ti["pass"])),
            (f"G4 stationary lag {lag}", bool(m["pass_stationary"])),
            (f"G4 timescales lag {lag}", bool(m["pass_timescales"])),
        ]
        L.append(
            f"| {lag} | {sci(ti['max_rel_error'])} {yn(ti['pass'])} | {m['n_active_conformatlas']} / {m['n_active_deeptime']} | {sci(m['max_abs_stationary_error'])} {yn(m['pass_stationary'])} | {sci(m['max_rel_timescale_error'])} {yn(m['pass_timescales'])} | {sci(dg['ts_rel_error_first_four_signed_order'])} / {sci(dg['ts_rel_error_all_five_abs_ordered'])} |"
        )
    L += [
        "",
        "The timescale failures are explained in `DEVIATIONS.md` D6: ConformAtlas 1.0.2, the code these gates were run with, ranked eigenvalues by signed value, deeptime by magnitude, and the reversible transition matrix has negative eigenvalues of large magnitude. The last column shows that ranking by |λ| reproduces deeptime. `dev` now ranks by |λ| (merge a1dac8e, CHANGELOG [Unreleased]); the registered G4 result was not re-run and stays recorded as FAIL.",
        "",
    ]

    # G5
    L += [
        "## G5 — Level 2, each tool's own default superposition (informational expectation: RMSIP of the top 10 modes ≥ 0.95)",
        "",
        "| Tool | RMSIP vs ConformAtlas default |",
        "|---|---|",
    ]
    for tool, m in g5["tools"].items():
        L.append(
            f"| {tool} | {m['rmsip']:.6f} |"
            if "rmsip" in m
            else f"| {tool} | error: {m['error']} |"
        )
    L.append("")

    # informational
    if g6:
        L += ["## Informational", ""]
        cp = g6["crystal_projection"]
        L += [
            "Crystal structures fitted on the CORE Cα atoms and projected into the trajectory's Cα PC space:",
            "",
            "| Structure | PC1 | PC2 | PC3 | percentile of the trajectory below (PC1, PC2, PC3) |",
            "|---|---|---|---|---|",
        ]
        for k, v in cp.items():
            L.append(
                f"| {k} | {v['PC1_PC2_PC3'][0]:.1f} | {v['PC1_PC2_PC3'][1]:.1f} | {v['PC1_PC2_PC3'][2]:.1f} | {', '.join(f'{x:.2f}' for x in v['percentile_in_trajectory'])} |"
            )
        L.append("")
        if g6.get("analyze_returncode") == 0:
            L += ["Default `conformatlas analyze` (Cα, one trajectory, 300 K):", ""]
            for key in (
                "analyze:states/state_free_energies.csv",
                "analyze:states/state_ensemble_summary.csv",
                "analyze:states/barriers.csv",
            ):
                rows = g6.get(key)
                if key.endswith("barriers.csv") and not rows:
                    L += ["`states/barriers.csv`: empty (a single major state, so no barrier between states).", ""]
                if rows:
                    cols = list(rows[0])
                    L += [
                        f"`{key.split(':')[1]}`",
                        "",
                        "| " + " | ".join(cols) + " |",
                        "|" + "---|" * len(cols),
                    ]
                    L += ["| " + " | ".join(str(r[c]) for c in cols) + " |" for r in rows]
                    L.append("")
            if g6.get("analyze_warnings"):
                L += [
                    "Warnings recorded by the run: "
                    + "; ".join(str(w) for w in g6["analyze_warnings"]),
                    "",
                ]

    # performance
    if perf:
        L += [
            "## Performance (reported, never gated)",
            "",
            "Median of 3 runs after one discarded warm-up, fresh process each, 8 BLAS threads. Stage: load → covariance → eigendecomposition → top-10 projections (no fit). Other jobs (a large background download) were running; see `ENVIRONMENT.md` and `results/performance_runs.csv` (load average recorded per run).",
            "",
            "| Selection | Tool | compute stage (s) | total wall (s) | peak memory (GB) | status |",
            "|---|---|---|---|---|---|",
        ]
        for e in perf:
            if e["status"] == "ok":
                L.append(
                    f"| {e['selection']} | {e['config']} | {e['compute_seconds']:.2f} | {e['wall_seconds']:.2f} | {e['peak_rss_gb']:.2f} | ok |"
                )
            else:
                L.append(f"| {e['selection']} | {e['config']} | | | | {e['status']} |")
        L.append("")

    n_pass = sum(1 for _, ok in gates if ok)
    fails = [n for n, ok in gates if not ok]
    L = (
        L[:2]
        + [
            "",
            f"**Gate summary: {n_pass} of {len(gates)} registered gates passed; {len(fails)} failed"
            + (": " + "; ".join(fails) if fails else "")
            + ".**",
        ]
        + L[2:]
    )
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:4]))


if __name__ == "__main__":
    main()
