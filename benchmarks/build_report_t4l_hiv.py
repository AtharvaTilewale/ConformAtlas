"""Build benchmarks/RESULTS_T4L_HIV.md from benchmarks/t4l/results/*.json and benchmarks/hiv/results/*.json.
No number is typed by hand. Criteria: CRITERIA_T4L_HIV.md; deviations: DEVIATIONS.md (D7-D10)."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
T = HERE / "t4l" / "results"
H = HERE / "hiv" / "results"


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def sci(x, nd=1):
    return "n/a" if x is None or x != x else f"{x:.{nd}e}"


def yn(b):
    return "PASS" if b else "FAIL"


def main() -> None:
    t12, t3, t4, t5, t6 = (
        load(T / f)
        for f in (
            "t1_t2.json",
            "t3_kinetics.json",
            "t4_null_test.json",
            "t5_force_field.json",
            "t6_replicates.json",
        )
    )
    h = load(H / "h_compare.json")
    perf = load(T / "performance_summary.json")
    gates: list[tuple[str, bool]] = []
    L = [
        "# T4 lysozyme and HIV-1 protease — results",
        "",
        "Generated by `benchmarks/build_report_t4l_hiv.py`. Pass criteria: `CRITERIA_T4L_HIV.md` (committed before any result). "
        "Departures: `DEVIATIONS.md` D7–D10. Failed gates are reported as failed.",
        "",
    ]

    # ---------------- T4L
    L += [
        "## T4 lysozyme (cysteine-free pseudo-wild type, 5 × 1 µs ff99SB*-ILDN + 3 × ~1.1 µs ff15ipq, 300 K)",
        "",
    ]
    t0 = t12["T0"]
    gates.append(("T0 integrity (whole molecules)", t0["pass"]))
    mx = max(v["max_consecutive_ca_A"] for v in t0["replicates"].values())
    L += [
        f"**T0 integrity: {yn(t0['pass'])}** — 8 replicates at 100 ps, frame counts as expected, largest consecutive Cα–Cα distance {mx:.2f} Å "
        "(after `gmx trjconv -pbc whole`; the deposited trajectories are broken across the box in most frames, DEVIATIONS D9).",
        "",
    ]
    L += [
        "### T1 — PCA numerics (pooled 5 ff99SB*-ILDN replicates, identical pre-fitted float32 coordinates; reference = NumPy covariance + `eigh`)",
        "",
        "| Selection (N × D) | Tool | rel. eigenvalue error | explained-variance error (pp) | 1 − \\|cos\\| (separated modes) | projection error / SD | gate |",
        "|---|---|---|---|---|---|---|",
    ]
    for sel in ("calpha", "heavy"):
        d = t12.get(f"T1_{sel}")
        if not d:
            continue
        for tool, m in d["tools"].items():
            if "error" in m:
                L.append(
                    f"| {sel} ({d['N']} × {d['D']}) | {tool} | error: {m['error'][:80]} | | | | FAIL |"
                )
                gates.append((f"T1 {sel} {tool}", False))
                continue
            g = m.get("pass")
            gate = "informational (randomised solver)" if g is None else yn(g)
            if g is not None:
                gates.append((f"T1 {sel} {tool}", bool(g)))
            L.append(
                f"| {sel} ({d['N']} × {d['D']}) | {tool} | {sci(m['max_rel_eigenvalue_error'])} | {sci(m['max_explained_abs_error_pct'])} | "
                f"{sci(m['max_one_minus_cos_separated'])} | {sci(m['max_projection_err_over_sd_separated'])} | {gate} |"
            )
    L.append("")
    if "T2" in t12:
        L += [
            "### T2 — free-energy landscape, Cα PC1–PC2",
            "",
            "| Grid | vs NumPy histogram (exact SI k_B, gate 1e-9 kJ/mol) | vs `gmx sham` (gate 1e-3 kJ/mol) |",
            "|---|---|---|",
        ]
        for n, d in t12["T2"].items():
            gates += [
                (f"T2 NumPy {n}", d["numpy"]["pass"]),
                (f"T2 sham {n}", d["gmx_sham"]["pass"]),
            ]
            L.append(
                f"| {n}×{n} ({d['numpy']['occupied_in_both']} occupied bins) | {sci(d['numpy']['max_abs_diff_kJ_mol'])} kJ/mol {yn(d['numpy']['pass'])} | "
                f"{sci(d['gmx_sham']['max_abs_diff_kJ_mol'])} kJ/mol {yn(d['gmx_sham']['pass'])} |"
            )
        L.append("")
    if t3:
        L += [
            "### T3 — kinetics vs deeptime (timescale-fix code; one shared k-means discretisation, 5 trajectories)",
            "",
            "| Lag (frames of 100 ps) | TICA md1us4 rel. error (gate 1e-8) | MSM active states | max \\|Δπ\\| (gate 1e-7) | max \\|ΔT\\| (gate 1e-7) | timescales rel. error (gate 1e-5) | pooled TICA (informational) |",
            "|---|---|---|---|---|---|---|",
        ]
        for lag, r in t3["lags"].items():
            m = r["msm"]
            gates += [
                (f"T3 TICA lag {lag}", r["tica_md1us4"]["pass"]),
                (f"T3 MSM lag {lag}", m["pass"]),
            ]
            L.append(
                f"| {lag} | {sci(r['tica_md1us4']['max_rel_error'])} {yn(r['tica_md1us4']['pass'])} | {m['n_active'][0]} / {m['n_active'][1]} | "
                f"{sci(m['max_abs_stationary'])} | {sci(m['max_abs_T'])} | {sci(m['max_rel_timescales'])} {yn(m['pass'])} | {sci(r['tica_pooled_informational']['max_rel_difference'])} |"
            )
        L.append("")
    if t4:
        gates.append(
            ("T4 null test of compare (bootstrap false-positive rate <= 0.15)", t4["pass"])
        )
        tab = pd.read_csv(T / "t4_null_test_table.csv")
        hw = ((tab.ci_high - tab.ci_low) / 2).median()
        sd = pd.concat([tab.A_replicate_sd_pct, tab.B_replicate_sd_pct]).median()
        L += [
            "### T4 — null test of `conformatlas compare` (all 10 splits of the 5 ff99SB*-ILDN replicates into 2 + 3)",
            "",
            f"**{yn(t4['pass'])}: bootstrap false-positive rate {t4['bootstrap_false_positive_rate']:.2f}** over {t4['n_split_state_pairs']} (split, state) pairs "
            f"(gate ≤ {t4['gate']}; nominal 0.05). Welch test on per-replicate populations: false-positive rate {t4['welch_false_positive_rate']:.2f} "
            f"(Welch p {tab.welch_p.min():.2f}–{tab.welch_p.max():.2f}).",
            "",
            f"Why: the replicates do not sample the same distribution. In the shared space one replicate (md1us4) is mostly in a second state while the "
            f"other four are mostly in the first, so whichever group holds md1us4 differs by {tab.difference_pp.abs().min():.0f}–{tab.difference_pp.abs().max():.0f} "
            f"percentage points. The block bootstrap resamples frames *within* replicates; its median 95 % half-width is {hw:.1f} pp, while the median "
            f"replicate-to-replicate SD is {sd:.1f} pp. The intervals therefore describe uncertainty given these particular trajectories, not the "
            "variability between independent simulations, and they are far too narrow for a between-condition claim. Per-split values: `t4l/results/t4_null_test_table.csv`.",
            "",
        ]
    if t5 and t5.get("population_table"):
        L += [
            "### T5 — force-field comparison, 5 ff99SB*-ILDN vs 3 ff15ipq (informational)",
            "",
            "| State | ff99SB*-ILDN % (replicate SD) | ff15ipq % (replicate SD) | difference (pp), bootstrap 95 % CI | Welch p |",
            "|---|---|---|---|---|",
        ]
        for r in t5["population_table"]:
            L.append(
                f"| {r['State']} | {r['ff99SBstar_Population_Percent']:.1f} ({r['ff99SBstar_Replicate_SD_Percent']:.1f}) | {r['ff15ipq_Population_Percent']:.1f} ({r['ff15ipq_Replicate_SD_Percent']:.1f}) | "
                f"{r['ff15ipq_minus_ff99SBstar_Percent']:.1f} [{r['ff15ipq_minus_ff99SBstar_CI95_Low']:.1f}, {r['ff15ipq_minus_ff99SBstar_CI95_High']:.1f}] | {r['ff15ipq_minus_ff99SBstar_Welch_p']:.3f} |"
            )
        so = t5.get("subspace_overlap.csv")
        if so:
            L.append(
                f"\nRMSIP between the two force fields' top-10 essential subspaces: {so[0]['ff15ipq']:.3f}. Given T4, only the replicate-level (Welch) test should be read as evidence of a difference."
            )
        L.append("")
    if t6:
        s = t6["rmsip_summary"]
        L += [
            "### T6 — replicate agreement (informational)",
            "",
            "| Pair type | RMSIP top-10 Cα modes, min / median / max |",
            "|---|---|",
        ]
        for k, v in s.items():
            L.append(
                f"| {k.replace('_', ' ')} | {v['min']:.2f} / {v['median']:.2f} / {v['max']:.2f} |"
            )
        verd = [
            v.get("convergence", {}).get("assessment")
            for v in t6["analyze"].values()
            if v.get("convergence")
        ]
        L += [
            "",
            "`conformatlas analyze` sampling verdict per replicate: "
            + "; ".join(
                f"{k}: {v.get('convergence', {}).get('assessment')}"
                for k, v in t6["analyze"].items()
            )
            + ".",
            "",
        ]
        _ = verd

    # ---------------- HIV
    if h:
        L += [
            "## HIV-1 protease (Sadiq et al. 2021; 964 × 130 ns, the authors' 100-state k-means on lambda coordinates)",
            "",
        ]
        gates.append(("H0 integrity", h["H0"]["pass"]))
        a, b = h["H1"]["vs_pyemma_fresh_sliding"], h["H1"]["vs_deeptime_sliding"]
        gates.append(
            (
                "H1 ConformAtlas MSM vs deeptime/PyEMMA (sliding counts, lag 300)",
                a["pass"] and b["pass"],
            )
        )
        L += [
            f"**H0 integrity: {yn(h['H0']['pass'])}.** **H1 (timescale-fix code): {yn(a['pass'] and b['pass'])}** — same 100-state active set; "
            f"max |Δπ| {sci(a['max_abs_stationary'])}, max |ΔT| {sci(a['max_abs_T'])}, top-5 timescales relative error {sci(a['max_rel_timescales'])} "
            "(gates 1e-6, 1e-6, 1e-5). PyEMMA 2.5.12 uses deeptime's estimator internally, so this is one independent reference (DEVIATIONS D7).",
            "",
        ]
        h2 = h["H2_informational"]
        L += [
            "**H2 (informational; the published model used PyEMMA's 'effective' counts):** slowest five implied timescales, ConformAtlas (sliding counts) vs the authors' saved model:",
            "",
            "| # | ConformAtlas (ns) | authors' model (ns) | ratio |",
            "|---|---|---|---|",
        ]
        for i, (x, y, r) in enumerate(
            zip(
                h2["timescales_ns"][0],
                h2["timescales_ns"][1],
                h2["timescale_ratio_conformatlas_over_saved"],
            ),
            1,
        ):
            L.append(f"| {i} | {x:.1f} | {y:.1f} | {r:.3f} |")
        h3 = h["H3_informational"]
        L += [
            "",
            "**H3 (informational): metastable states.** ConformAtlas PCCA+ (5 sets) on the H1 model: set probabilities "
            + ", ".join(f"{p:.3f}" for p in sorted(h3["pcca_set_stationary"], reverse=True))
            + f". deeptime PCCA+ on the same matrix gives the same crisp sets (stationary-weighted agreement {h3['deeptime_pcca']['stationary_weighted_crisp_agreement_with_conformatlas']:.3f}; "
            f"max membership difference {h3['deeptime_pcca']['max_abs_membership_difference_best_permutation']:.3f}). "
            + (
                f"The authors' 5-state HMM (probabilities {', '.join(f'{p:.3f}' for p in sorted(h3['hmm_pi'], reverse=True))}) assigns microstates differently "
                f"(stationary-weighted agreement with PCCA+ {h3['stationary_weighted_agreement_best_permutation']:.2f}): a property of HMM vs PCCA+ coarse-graining, not of ConformAtlas."
                if "hmm_pi" in h3
                else ""
            ),
            "",
        ]
        rows = h["H4_informational"]["rows"]
        L += [
            "**H4 (informational): implied-timescale scan** vs the authors' saved scan (Bayesian, effective counts): ratio of the slowest timescale at each lag "
            + ", ".join(f"{r['lag']}: {r['ratio_ts1']:.3f}" for r in rows)
            + ".",
            "",
        ]

    # ---------------- performance
    if perf:
        L += [
            "## Performance (reported, never gated)",
            "",
            "Pooled 100 ps data: median of 3 runs after one discarded warm-up; 1 ps data (1,000,001 frames): one run. Fresh process, 8 BLAS threads, 1800 s timeout, no superposition.",
            "",
            "| Dataset | Selection | Tool | compute stage (s) | wall (s) | peak memory (GB) | status |",
            "|---|---|---|---|---|---|---|",
        ]
        for e in perf:
            if e["status"] == "ok":
                L.append(
                    f"| {e['dataset']} | {e['selection']} | {e['config']} | {e['compute_seconds']:.1f} | {e['wall_seconds']:.1f} | {e['peak_rss_gb']:.2f} | ok |"
                )
            else:
                L.append(
                    f"| {e['dataset']} | {e['selection']} | {e['config']} | | | | {e['status']} |"
                )
        L.append("")

    n_pass = sum(1 for _, ok in gates if ok)
    fails = [n for n, ok in gates if not ok]
    L = (
        L[:2]
        + [
            f"**Gate summary: {n_pass} of {len(gates)} registered gates passed; {len(fails)} failed"
            + (": " + "; ".join(fails) if fails else "")
            + ".**",
            "",
        ]
        + L[2:]
    )
    (HERE / "RESULTS_T4L_HIV.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:4]))


if __name__ == "__main__":
    main()
